"""SC-M26 eval: SC-S1's frozen items (2,920) through V1's runner (v1_value_hook/evalrun.run: chunks, one nudge for an
unparsed decision, records appended to OUT/eval_{cell}.jsonl, resumable), generated by OpenAI's chat API.

  uv run python -m self_concept.m26_frontier.evalrun --cell G-W_s1 [--model ft:...] --out self_concept/m26_frontier/results/main
--model defaults to the cell's fine-tuned model in results/jobs.json (G-BASE_s0: gpt-4.1-mini-2025-04-14 itself).
Decoding is V1's (temperature 0.7, top_p 0.95; max 400 tokens; the gen block greedy, max 16; the item's seed); top_k and
min_p have no OpenAI equivalent and are dropped. Replies are stored in the engine's form (vigilante api_gen.canon:
text, then any tool calls as Qwen XML), so V1's and SC-S1's scorers read them unchanged. Spend = usage tokens x
OpenAI's rates, booked to self_concept/ledger.jsonl as it accrues; the run stops (resumable) before passing the cap.
V1_FAKE_GEN=1 answers from SC-S1's fake_gen (no calls).
"""
import argparse
import json
import os
import threading
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import self_concept.common.ledger as L
from self_concept.m26_frontier import ft as FT

PRICES = {"ft": (0.80, 0.20, 3.20), "base": (0.40, 0.10, 1.60)}   # $/1M: input, cached input, output
PLANNED_EVAL = 9.0          # 6 fine-tuned cells x ~$1.25 + the base ~$0.65, rounded up
WORKERS, TRIES = 16, 6


class OAGen:
    def __init__(self, model, cap_left):
        self.model, self.cap_left = model, cap_left
        self.price = PRICES["ft" if model.startswith("ft:") else "base"]
        self.key = FT.key()
        self.spent, self.lock = 0.0, threading.Lock()
        self.book = L.Booker(FT.MINI, "api", f"openai:{model}")
        self.errors = {}

    def _body(self, b):
        from persona.operative import frontier as F
        s = b["sampling"]
        body = {"model": self.model, "messages": F.to_openai(b["messages"]), "temperature": s["temperature"],
                "max_tokens": s["max_tokens"], "seed": s["seed"] & 0x7FFFFFFF}
        if "top_p" in s:
            body["top_p"] = s["top_p"]
        if b.get("tools"):
            body["tools"], body["tool_choice"], body["parallel_tool_calls"] = b["tools"], "auto", False
        return body

    def _one(self, b):
        from vigilante.src.api_gen import canon
        body = json.dumps(self._body(b)).encode()
        for k in range(TRIES):
            with self.lock:
                if self.spent >= self.cap_left:
                    raise SystemExit(f"[m26-eval] stopping: spend ${self.spent:.2f} reached the cap left")
            req = urllib.request.Request(f"{FT.API}/chat/completions", data=body, method="POST",
                                         headers={"Authorization": f"Bearer {self.key}", "Content-Type": "application/json"})
            try:
                with urllib.request.urlopen(req, timeout=180) as r:
                    resp = json.loads(r.read())
            except urllib.error.HTTPError as e:
                if e.code in (429, 500, 502, 503, 504) and k < TRIES - 1:
                    time.sleep(2 * 2 ** k)
                    continue
                with self.lock:
                    self.errors[f"http{e.code}"] = self.errors.get(f"http{e.code}", 0) + 1
                return "", f"error:http_{e.code}"
            except Exception as e:  # noqa: BLE001 (timeouts, resets)
                if k < TRIES - 1:
                    time.sleep(2 * 2 ** k)
                    continue
                return "", f"error:{type(e).__name__}"
            u = resp.get("usage") or {}
            cached = (u.get("prompt_tokens_details") or {}).get("cached_tokens") or 0
            usd = ((u.get("prompt_tokens", 0) - cached) * self.price[0] + cached * self.price[1]
                   + u.get("completion_tokens", 0) * self.price[2]) / 1e6
            with self.lock:
                self.spent += usd
            self.book.add(usd)
            ch = resp["choices"][0]
            msg = ch["message"]
            calls = []
            for tc in msg.get("tool_calls") or []:
                try:
                    args = json.loads(tc["function"].get("arguments") or "{}")
                except json.JSONDecodeError:
                    args = {"_raw": tc["function"].get("arguments")}
                calls.append((tc["function"]["name"], args if isinstance(args, dict) else {"_raw": args}))
            return canon(msg.get("content") or "", calls, None, False), str(ch.get("finish_reason") or "unknown")
        return "", "error:retries"

    def __call__(self, batch):
        try:
            with ThreadPoolExecutor(WORKERS) as ex:
                return list(ex.map(self._one, batch))
        finally:
            self.book.flush()


def model_of(cell):
    if cell == "G-BASE_s0":
        return FT.BASE_MODEL
    jobs = json.loads(FT.JOBS.read_text())
    m = jobs[cell.split("-", 1)[1]].get("model")
    if not m:
        raise SystemExit(f"[m26-eval] {cell}: no fine-tuned model yet")
    return m


def main(argv=None):
    from persona_affect.v1_value_hook import evalrun as R
    from self_concept.s1_scale import evalrun as S1E
    from self_concept.s1_scale.items import items
    ap = argparse.ArgumentParser(prog="m26 evalrun")
    ap.add_argument("--cell", required=True)
    ap.add_argument("--model")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if os.environ.get("V1_FAKE_GEN") == "1":
        R.run("fake", a.cell, [], a.out, items=items(), gen=S1E.fake_gen)
        return
    left = FT.CAP - L.ledger_total(FT.MINI)
    gen = OAGen(a.model or model_of(a.cell), left)
    try:
        R.run(gen.model, a.cell, [], a.out, items=items(), gen=gen)
    finally:
        gen.book.flush()
        Path(a.out, f"spend_{a.cell}.json").write_text(json.dumps({"model": gen.model, "usd": gen.spent,
                                                                    "errors": gen.errors}))
        print(f"[m26-eval] {a.cell}: ${gen.spent:.3f}, errors {gen.errors}")


if __name__ == "__main__":
    main()
