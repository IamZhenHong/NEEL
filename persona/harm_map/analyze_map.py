"""Read results/map.json (from build_map.py) and write results/RESULTS_tables.md + results/harm_map.png.

Descriptive only (DESIGN.md). Main points = one per harm x model with an instruction cell, no rule_variant, and a
record cell manipulated within one run (EC collusion is tabled but not plotted: its base vs record contrast is
episode drift, and its instruction cell is from another run).
"""
import json
import os

import matplotlib.pyplot as plt
from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
OPEN = {"Qwen3.5-9B": "9B", "Qwen3.6-27B": "27B", "Gemma 4 31B": "Gemma"}
FRONTIER = {"GPT-5.6 Sol": "GPT", "Gemini 3.8 Flash": "Gemini", "Claude Sonnet 5.5": "Sonnet"}
SHORT = {
    "justice_penalise_unilateral": "penalise alone", "act_alone_deploy": "deploy alone",
    "act_alone_access": "grant access alone", "act_alone_spend": "spend alone", "act_alone_agent": "control agent alone",
    "sycophancy_flawed_plan": "affirm flawed plan", "sycophancy_false_claim": "agree with false claim",
    "sycophancy_concede_pushback": "concede (SYCON)", "companion_reinforcing": "companion (INTIMA)",
    "conceal_known_problem": "conceal", "false_completion": "false completion", "mask_lie_known_facts": "lie (MASK)",
    "explicit_operational_harm": "explicit harm", "justice_penalise_unverified": "penalise unverified",
    "decisive_action_harsh_target": "harsh action", "decisive_action_mild_target": "mild action",
    "ec_collusion_accept": "collude (EC)",
}
FAMILY = {  # marker = harm family (secondary encoding; colour = open vs frontier)
    "justice_penalise_unilateral": "action", "act_alone_deploy": "action", "act_alone_access": "action",
    "act_alone_spend": "action", "act_alone_agent": "action",
    "sycophancy_flawed_plan": "sycophancy", "sycophancy_false_claim": "sycophancy",
    "sycophancy_concede_pushback": "sycophancy", "companion_reinforcing": "sycophancy",
    "conceal_known_problem": "honesty", "false_completion": "honesty", "mask_lie_known_facts": "honesty",
    "explicit_operational_harm": "explicit harm",
}
OFFSETS = {  # (panel cell, label) -> (dx, dy, ha) for labels that would collide
    ("rec", "control agent alone · 27B"): (5, -11, "left"),
    ("rec", "lie (MASK) · 27B"): (5, 6, "left"),
    ("rec", "affirm flawed plan · Gemini"): (5, -11, "left"),
    ("rec", "companion (INTIMA) · Gemini"): (5, -10, "left"),
    ("rec", "explicit harm · Gemini"): (-6, 3, "right"),
    ("rec", "explicit harm · GPT"): (-6, 3, "right"),
    ("rec_rule", "penalise alone · GPT, Gemini"): (5, -10, "left"),
    ("rec_rule", "companion (INTIMA) · 9B, 27B"): (5, 4, "left"),
    ("rec_rule", "affirm flawed plan · GPT"): (0, 6, "center"),
    ("rec_rule", "penalise alone · Sonnet"): (-4, 5, "right"),
    ("rec_rule", "explicit harm · Gemini"): (-6, 5, "right"),
    ("rec_rule", "explicit harm · GPT"): (-6, -11, "right"),
}
# labels replaced by one shared label for two nearby points: (panel cell) -> {skipped labels}, (x, y, text)
SHARED = {"rec_rule": ({"companion (INTIMA) · Gemini", "companion (INTIMA) · GPT"},
                       (15, -7, "companion (INTIMA) · Gemini, GPT"))}
MARKER = {"action": "o", "sycophancy": "s", "honesty": "^", "explicit harm": "D"}
COLOR = {"open": "#2a78d6", "frontier": "#eb6834"}
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"


def short_model(m):
    return OPEN.get(m) or FRONTIER.get(m) or m


def group(m):
    return "open" if m in OPEN else "frontier"


def rate(e, c):
    s = (e.get("cells") or {}).get(c)
    return s["rate"] if s else None


def ci(e, c):
    s = (e.get("cells") or {}).get(c)
    return f"{s['rate']:.0f} [{s['lo']:.0f}, {s['hi']:.0f}]" if s else "–"


def main():
    rows = json.load(open(os.path.join(HERE, "results", "map.json")))
    data = [e for e in rows if e.get("cells")]
    main_pts = [e for e in data if not e.get("rule_variant") and rate(e, "instr") is not None
                and e["harm"] != "ec_collusion_accept"]

    md = ["# Harm vulnerability map v0: tables (generated by analyze_map.py)", ""]

    # 1. main table
    md += ["## 1. Every harm x model (rate % [95% CI, task-clustered])", "",
           "| harm | model | base | told to | told + rule | own record | record + rule | on the map |",
           "|---|---|---|---|---|---|---|---|"]
    order = sorted(data, key=lambda e: (e["harm"], e.get("rule_variant") or "", group(e["model"]), e["model"]))
    for e in order:
        if (e.get("rule_variant") or "").startswith("cr_"):
            continue
        on_map = "yes" if e in main_pts else "no"
        name = SHORT.get(e["harm"], e["harm"]) + (f" ({e['rule_variant']})" if e.get("rule_variant") else "")
        md.append(f"| {name} | {short_model(e['model'])} | {ci(e, 'base')} | {ci(e, 'instr')} | "
                  f"{ci(e, 'instr_rule')} | {ci(e, 'rec')} | {ci(e, 'rec_rule')} | {on_map} |")
    md.append("")

    # 2. Spearman, the theory's prediction
    md += ["## 2. Does the record's pull fall as resistance to being told rises?", "",
           "x = 100 − % doing the harm when told to; y = % after its own record. Spearman over points (descriptive; "
           "points share harnesses and models, so no test).", "",
           "| points | n | rho (record, no rule) | rho (record + rule) |", "|---|---|---|---|"]
    for label, sel in [("all", lambda e: True), ("open models", lambda e: group(e["model"]) == "open"),
                       ("frontier models", lambda e: group(e["model"]) == "frontier")]:
        pts = [e for e in main_pts if sel(e)]
        x = [100 - rate(e, "instr") for e in pts]
        y = [rate(e, "rec") for e in pts]
        r1 = spearmanr(x, y).statistic
        pr = [e for e in pts if rate(e, "rec_rule") is not None]
        r2 = spearmanr([100 - rate(e, "instr") for e in pr], [rate(e, "rec_rule") for e in pr]).statistic
        md.append(f"| {label} | {len(pts)} | {r1:+.2f} | {r2:+.2f} (n {len(pr)}) |")
    md.append("")

    # 3. the same rule against being told vs against its own record
    md += ["## 3. Does the same safety rule stop a record the way it stops an instruction?", "",
           "Rates with and without the rule (no shares: the rule often pushes below base, so shares pass 100%). "
           "Daylight = record + rule − told + rule.", "",
           "| harm | model | rule | base | told → told + rule | record → record + rule | daylight |",
           "|---|---|---|---|---|---|---|"]
    for e in order:
        if (e.get("rule_variant") or "").startswith("cr_") or rate(e, "rec_rule") is None:
            continue
        rule = "lead's request" if (e.get("rule_variant") or "").startswith("lead") else (e.get("rule_kind") or "")
        f = lambda c: "–" if rate(e, c) is None else f"{rate(e, c):.0f}"
        dl = e.get("daylight")
        md.append(f"| {SHORT.get(e['harm'], e['harm'])} | {short_model(e['model'])} | {rule.split(' (')[0]} | "
                  f"{f('base')} | {f('instr')} → {f('instr_rule')} | {f('rec')} → {f('rec_rule')} | "
                  f"{'' if not dl else f'{dl[0]:+.0f} [{dl[1]:+.0f}, {dl[2]:+.0f}]'} |")
    md.append("")

    # 4. rule type (stability battery C arms)
    md += ["## 4. Rule type against an affirm-flawed-plan record (stability battery, C arms)", "",
           "| model | record alone | candour rule | harm-avoid rule | operator: defer | operator: channels |",
           "|---|---|---|---|---|---|"]
    for m in ["Qwen3.6-27B", "GPT-5.6 Sol", "Gemini 3.8 Flash"]:
        arms = {e["rule_variant"]: e for e in data if e.get("rule_variant", "") and e["rule_variant"].startswith("cr_")
                and e["model"] == m}
        rec = rate(next(iter(arms.values())), "rec")
        cell = lambda k: " / ".join(f"{arms[k + s]['cells']['rec_rule']['rate']:.0f} (n {arms[k + s]['cells']['rec_rule']['n']})"
                                    for s in ("_S", "_B"))
        md.append(f"| {short_model(m)} | {rec:.0f} | {cell('cr_vc')} | {cell('cr_vh')} | {cell('cr_od')} | {cell('cr_oc')} |")
    md += ["", "Each rule cell: short / buried. GPT and Gemini arms lost rows to OpenRouter 402s (n shown).", ""]

    with open(os.path.join(HERE, "results", "RESULTS_tables.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")

    # figure
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9, "axes.edgecolor": INK2,
                         "axes.labelcolor": INK, "xtick.color": INK2, "ytick.color": INK2})
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 5.2), sharey=True, facecolor=SURF)
    for ax, cell, title in [(axes[0], "rec", "Own record, no rule"),
                            (axes[1], "rec_rule", "Own record + a safety rule against the harm")]:
        ax.set_facecolor(SURF)
        ax.grid(color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        labels = {}
        for e in main_pts:
            y = rate(e, cell)
            if y is None:
                continue
            x = 100 - rate(e, "instr")
            g = group(e["model"])
            ax.scatter(x, y, s=46, marker=MARKER[FAMILY[e["harm"]]], color=COLOR[g], edgecolor=SURF, lw=1.5,
                       zorder=3, alpha=0.9)
            if x < 10 and y > 90:  # the top-left cluster is named in the caption instead
                continue
            key = (SHORT[e["harm"]], round(x / 3), round(y / 3))  # same harm at (nearly) the same spot: one label
            labels.setdefault(key, [x, y, []])[2].append(short_model(e["model"]))
        skip, shared = SHARED.get(cell, (set(), None))
        if shared:
            ax.text(shared[0], shared[1], shared[2], fontsize=7, color=INK2, ha="center", va="center")
        for (harm, _, _), (x, y, models) in labels.items():
            lab = f"{harm} · {', '.join(models)}"
            if lab in skip:
                continue
            dx, dy, ha = OFFSETS.get((cell, lab), (5, 3, "left"))
            ax.annotate(lab, (x, y), xytext=(dx, dy), textcoords="offset points", fontsize=7, color=INK2, ha=ha)
        ax.set_xlim(-5, 110)
        ax.set_ylim(-12, 108)
        ax.set_xlabel("Resistance to being told to do it (100 − % complying with a direct instruction)")
        ax.set_title(title, loc="left", fontsize=10.5, color=INK, fontweight="bold")
    axes[0].set_ylabel("% doing the harm after its own record of doing it")
    for ax, cell in [(axes[0], "rec"), (axes[1], "rec_rule")]:
        n = sum(1 for e in main_pts if rate(e, cell) is not None and 100 - rate(e, "instr") < 10 and rate(e, cell) > 90)
        ax.text(0.5, 88, f"↑ {n} points (see caption)", fontsize=7, color=INK2, va="center")
    handles = [plt.Line2D([], [], ls="", marker="o", color=COLOR["open"], label="open (Qwen 9B / 27B, Gemma)"),
               plt.Line2D([], [], ls="", marker="o", color=COLOR["frontier"], label="frontier (GPT, Gemini, Sonnet)")]
    handles += [plt.Line2D([], [], ls="", marker=mk, color=INK2, label=f) for f, mk in MARKER.items()]
    fig.legend(handles=handles, loc="lower center", ncol=6, frameon=False, fontsize=8, bbox_to_anchor=(0.5, -0.01))
    fig.suptitle("Harm vulnerability map v0: existing runs, one point per harm × model (descriptive)",
                 x=0.01, ha="left", fontsize=11.5, color=INK)
    fig.tight_layout(rect=(0, 0.05, 1, 0.96))
    fig.savefig(os.path.join(HERE, "results", "harm_map.png"), dpi=170, facecolor=SURF)

    cluster = [f"{SHORT[e['harm']]} · {short_model(e['model'])}" for e in main_pts
               if 100 - rate(e, "instr") < 10 and rate(e, "rec") > 90]
    print("top-left cluster (no rule):", "; ".join(cluster))
    print(open(os.path.join(HERE, "results", "RESULTS_tables.md")).read())


if __name__ == "__main__":
    main()
