def parse_trust(text):
    m = re.search(r"\b(turns|log)\b", (text or "").lower())
    return m.group(1) if m else None


def decide_trust(gen, items):
    texts = gen([it["messages"] for it in items], [it["seed"] for it in items], False, 60)
    ok = [parse_trust(t) is not None for t in texts]
    again = [j for j, x in enumerate(ok) if not x]
    if again:
        t2 = gen([items[j]["messages"] + [{"role": "assistant", "content": texts[j]}, {"role": "user", "content": TRUST_NUDGE}]
                  for j in again], [items[j]["seed"] + 1 for j in again], False, 60)
        for j, t in zip(again, t2):
            texts[j] += "\n\n[nudge]\n\n" + t
    return texts, ok


def write(f, ch, texts, vis, ok):
    for it, t, v, ft in zip(ch, texts, vis, ok):
        oid = parse_option(v)
        rec = {k: x for k, x in it.items() if k not in ("messages", "amap")} | {
            "text": t, "first_try": ft, "option": oid, "mode": it["amap"].get(oid)}
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def write_trust(f, ch, texts, ok):
    for it, t, ft in zip(ch, texts, ok):
        ans = parse_trust(t.split("[nudge]")[-1])
        rec = {k: x for k, x in it.items() if k not in ("messages", "amap")} | {
            "text": t, "first_try": ft, "option": ans, "mode": ans}
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def run(a):
    from vllm import LLM
    t0 = time.time()
    llm = LLM(model=a.model, dtype="bfloat16", max_model_len=MAX_LEN, gpu_memory_utilization=0.88, seed=0,
              enable_prefix_caching=True, limit_mm_per_prompt={"image": 0, "video": 0})
    gen = O.make_gen(llm, llm.get_tokenizer())
    log = lambda m: print(m, flush=True)  # noqa: E731
    log(f"[op2] loaded {a.model} in {time.time() - t0:.0f}s")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    groups = tuple(a.groups.split(","))
    items = build_items(a.model, groups)
    done = set()
    if (out / "op2.jsonl").exists():
        done = {json.loads(l)["key"] for l in open(out / "op2.jsonl")}
    todo = [it for it in items if it["key"] not in done]
    log(f"[op2] {len(items)} items: " + ", ".join(f"{g} {sum(it['group'] == g for it in items)}" for g in groups)
        + f"; {len(done)} already done, {len(todo)} to go")
    trust, main = [it for it in todo if it["kind"] == "trust"], [it for it in todo if it["kind"] == "decide"]
    with open(out / "op2.jsonl", "a") as f:
        if trust:
            write_trust(f, trust, *decide_trust(gen, trust))
            f.flush()
            log(f"[op2] trust branch {len(trust)} ({time.time() - t0:.0f}s)")
        for c0 in range(0, len(main), 512):
            ch = main[c0:c0 + 512]
            write(f, ch, *O.decide(gen, ch))
            f.flush()
            log(f"[op2] {min(c0 + 512, len(main))}/{len(main)} ({time.time() - t0:.0f}s)")
    (out / "run_info.json").write_text(json.dumps({"model": a.model, "groups": groups, "n": len(items),
                                                   "seconds": round(time.time() - t0)}))
    log(f"[op2] done ({time.time() - t0:.0f}s)")


