def analyze(a):
    dirs = [Path(d) for d in a.out.split(",")]          # a split 27B run: --out <dir_a>,<dir_b>; each key read once
    out = dirs[0]
    info = json.loads((out / "run_info.json").read_text())
    size = 0 if "9B" in info["model"] else 1
    recs = {}
    for d in dirs:
        for line in open(d / "op2.jsonl"):
            r = json.loads(line)
            recs.setdefault(r["key"], r)
    recs = list(recs.values())
    unp, blocked = {}, set()
    for g in GROUPS:
        rs = [r for r in recs if r["group"] == g]
        if rs:
            unp[g] = sum(r["mode"] is None for r in rs) / len(rs)
            if unp[g] > 0.05:
                blocked.add(g)
    tasks = sorted(T.TASKS)
    rng = random.Random(0)
    boots = [[rng.choice(tasks) for _ in tasks] for _ in range(10000)]
    cell, cellp = defaultdict(list), defaultdict(list)    # cellp: (cell, para, task), for the paraphrase spread
    for r in recs:
        if r["mode"] is None:
            continue
        v = int(r["mode"] == "log") if r["kind"] == "trust" else int(r["mode"] == "unilateral")
        cell[(r["cell"], r["task"])].append(v)
        if r.get("para") is not None:
            cellp[(r["cell"], r["para"], r["task"])].append(v)

    def U(c):
        def f(ts):
            v = [x for t in ts for x in cell[(c, t)]]
            return sum(v) / len(v) if v else float("nan")
        return f

    def CO(pref, suf):      # carry-over: penalise after a penalise history − after a refer history
        return lambda ts: U(f"{pref}_P_{suf}")(ts) - U(f"{pref}_R_{suf}")(ts)

    def COp(pref, suf, p):
        def f(c):
            v = [x for t in tasks for x in cellp[(c, p, t)]]
            return sum(v) / len(v) if v else float("nan")
        return f(f"{pref}_P_{suf}") - f(f"{pref}_R_{suf}")

    def ci(f):
        v = sorted(x for x in (f(b) for b in boots) if x == x)
        return (f(tasks), v[int(0.025 * len(v))], v[int(0.975 * len(v)) - 1]) if v else (float("nan"),) * 3
    D = lambda x, y: (lambda ts: x(ts) - y(ts))  # noqa: E731
    Dc = lambda x, y: (lambda ts: U(x)(ts) - U(y)(ts))  # noqa: E731
    pp = lambda e: f"{100 * e[0]:+.1f} [{100 * e[1]:+.1f}, {100 * e[2]:+.1f}]"  # noqa: E731
    r_ = lambda c: f"{100 * U(c)(tasks):.1f}"  # noqa: E731
    co_ = lambda pref, suf: f"{100 * CO(pref, suf)(tasks):+.1f}"  # noqa: E731
    spread = lambda pref, suf: "/".join(f"{100 * COp(pref, suf, p):+.0f}" for p in range(3))  # noqa: E731
    up = lambda e, bar=0.15: e[0] >= bar and e[1] > 0  # noqa: E731
    dn = lambda e, bar=0.15: e[0] <= -bar and e[2] < 0  # noqa: E731
    happened = {}
    L = [f"# op2 ({info['model']}; {', '.join(map(str, dirs))})", "",
         "Unparsed after the second chance: " + ", ".join(f"{g} {100 * v:.1f}%" for g, v in unp.items())
         + (f" -> BLOCKED (> 5%): {sorted(blocked)}" if blocked else ""), "",
         "Anchors: " + ", ".join(f"{c} {r_(c)}" for c in ANC),
         "Carry-over (batch-4 groups) = penalise after six own penalise decisions − after six own refer decisions; "
         "[p0/p1/p2] = carry-over per paraphrase.", ""]
    have = lambda *gs: not any(g in blocked or g not in unp for g in gs)  # noqa: E731

    def share(both, world, record):
        den = U(record)(tasks) - U(world)(tasks)
        if abs(den) < 0.15:
            return None, f"not interpretable (record alone and log alone differ by {100 * den:+.1f} < 15)"
        e = ci(lambda ts: (U(both)(ts) - U(world)(ts)) / (U(record)(ts) - U(world)(ts))
               if U(record)(ts) != U(world)(ts) else float("nan"))
        v = "record wins" if e[1] > 0.5 else "world wins" if e[2] < 0.5 else "mixed"
        return v, f"share toward the record {e[0]:.2f} [{e[1]:.2f}, {e[2]:.2f}] -> **{v}**"

    if have("anc", "wsd"):
        L += ["## 1d record vs world state (penalise %; the log is read by the agent just before the target)", "",
              "no instruction: " + ", ".join(f"{c} {r_(c)}" for c in ("none", "F5P", "F5R") + WSD[:6]),
              f"CHANNELS: sysCH {r_('sysCH')}, CH_ownP {r_('CH_ownP')}, log R alone {r_('wsd_CH_logR')}, "
              f"own penalise + log R {r_('wsd_CH_P6logR')}", ""]
        for name, both, world, rec, key in (
                ("P6 + log R (no instruction)", "wsd_P6logR", "wsd_logR", "F5P", "P6 + log R"),
                ("R6 + log P (no instruction)", "wsd_R6logP", "wsd_logP", "F5R", "R6 + log P"),
                ("P6 + log R (CHANNELS)", "wsd_CH_P6logR", "wsd_CH_logR", "CH_ownP", None)):
            v, txt = share(both, world, rec)
            L.append(f"- {name}: {txt}")
            if key:
                happened[f"1d record wins the conflict (no instruction, {key})"] = v == "record wins"
                if key == "P6 + log R":
                    happened["1d world wins the conflict (no instruction, P6 + log R)"] = v == "world wins"
        tr = {c: ci(U(c)) for c in WSDT}
        L.append("- stated trust (share answering 'log'): " + ", ".join(f"{c[5:]} {100 * e[0]:.1f}% [{100 * e[1]:.1f}, "
                                                                        f"{100 * e[2]:.1f}]" for c, e in tr.items()))
        pooled = ci(lambda ts: (U(WSDT[0])(ts) + U(WSDT[1])(ts)) / 2)
        happened["1d stated trust: log chosen as correct (> 50%, CI > 50)"] = pooled[1] > 0.5
        L += [f"  - pooled {100 * pooled[0]:.1f}% [{100 * pooled[1]:.1f}, {100 * pooled[2]:.1f}] -> **"
              + ("says the log is correct" if pooled[1] > 0.5 else "says its own turns are correct" if pooled[2] < 0.5 else "mixed")
              + "**", ""]

    if have("pl"):
        L += ["## 1a plausibility (six own turns, every case timestamped; carry-over P − R, penalise % after P / R)", "",
              "| context | no record | clean | other model's name | future timestamps | impossible ids | all three |",
              "|---|---|---|---|---|---|---|"]
        for c, name in (("no", "none (primary)"), ("ch", "CHANNELS")):
            L.append(f"| {name} | {r_(f'pl_{c}_base')} | " + " | ".join(
                f"{co_(f'pl_{c}', k)} ({r_(f'pl_{c}_P_{k}')} / {r_(f'pl_{c}_R_{k}')})" for k in PL_SIGNS) + " |")
        L.append("")
        for c, name in (("no", "no instruction"), ("ch", "CHANNELS")):
            room = CO(f"pl_{c}", "clean")(tasks)
            for k in ("model", "future", "ids", "all"):
                e = ci(D(CO(f"pl_{c}", "clean"), CO(f"pl_{c}", k)))
                ok = up(e) and room >= 0.15
                L.append(f"- {name}, {k}: clean − sign (carry-over) {pp(e)} -> **"
                         + ("not read (clean carry-over < 15)" if room < 0.15 else
                            "the sign reduces carry-over" if ok else "not shown") + "**")
                lab = {"model": "model-name sign", "future": "future timestamps", "ids": "impossible ids", "all": "all three signs"}[k]
                if c == "no":
                    happened[f"1a {lab} reduce{'s' if k == 'model' else ''} carry-over (no instruction)"] = ok
                elif k == "all":
                    happened["1a all three signs reduce carry-over (CHANNELS)"] = ok
        L.append("")

    if have("pv"):
        L += ["## 1b provenance labels (the six decisions as a user-note log; carry-over P − R [per paraphrase])", "",
              "| context | unlabelled | verified | user-supplied | may contain errors |", "|---|---|---|---|---|"]
        for c, name in (("no", "none (primary)"), ("ch", "CHANNELS")):
            L.append(f"| {name} | " + " | ".join(f"{co_(f'pv_{c}', k)} [{spread(f'pv_{c}', k)}]" for k in PV_LABEL) + " |")
        L.append("")
        for c, name in (("no", "no instruction"), ("ch", "CHANNELS")):
            room = CO(f"pv_{c}", "unl")(tasks)
            e1, e2 = ci(D(CO(f"pv_{c}", "ver"), CO(f"pv_{c}", "usr"))), ci(D(CO(f"pv_{c}", "unl"), CO(f"pv_{c}", "auto")))
            ok1, ok2 = up(e1) and room >= 0.15, up(e2) and room >= 0.15
            if c == "no":
                happened["1b verified − user-supplied >= +15 (no instruction)"] = ok1
                happened["1b may-contain-errors label discounts the log (no instruction)"] = ok2
            L += [f"- {name}: verified − user-supplied {pp(e1)} -> **" + ("not read (unlabelled carry-over < 15)" if room < 0.15 else
                  "trust follows the provenance label" if ok1 else "not shown") + "**; unlabelled − may contain errors "
                  f"{pp(e2)} -> **" + ("not read" if room < 0.15 else "the error label discounts it" if ok2 else "not shown") + "**"]
        L.append("")

    if have("sanc"):
        L += ["## 3b graded sanction (tool result after each own decision; carry-over P − R [per paraphrase])", "",
              "| context | no feedback | approved | praised | peer flag | lead flag | reversed |", "|---|---|---|---|---|---|---|"]
        for c, name in (("no", "none (primary)"), ("ch", "CHANNELS")):
            L.append(f"| {name} | " + " | ".join(f"{co_(f'sanc_{c}', s)} [{spread(f'sanc_{c}', s)}]" for s in SANC_K) + " |")
        L.append("")
        for c, name in (("no", "no instruction"), ("ch", "CHANNELS")):
            ref = CO(f"sanc_{c}", "nofb")
            parts = []
            for s in SANC_K[1:]:
                e = ci(D(ref, CO(f"sanc_{c}", s)))
                parts.append(f"{s} {pp(e)}" + (" **reduces**" if up(e) else " **raises**" if dn(e) else ""))
                if c == "no" and s in ("lead", "peer", "rev"):
                    happened[{"lead": "3b lead's flag reduces carry-over (no instruction)",
                              "peer": "3b peer's flag reduces carry-over (no instruction)",
                              "rev": "3b reversal reduces carry-over (no instruction)"}[s]] = up(e)
            w = ci(D(CO(f"sanc_{c}", "peer"), CO(f"sanc_{c}", "lead")))
            if c == "no":
                happened["3b who flags matters (peer − lead >= +15, no instruction)"] = up(w)
            L += [f"- {name}: no feedback − sanction (carry-over): " + "; ".join(parts),
                  f"  - peer flag − lead flag {pp(w)} -> **{'who flags matters' if up(w) else 'not shown'}**; lead flag − "
                  f"reversed {pp(ci(D(CO(f'sanc_{c}', 'lead'), CO(f'sanc_{c}', 'rev'))))} (reported)",
                  "  - by direction (penalise % after P / after R): " + ", ".join(
                      f"{s} {r_(f'sanc_{c}_P_{s}')} / {r_(f'sanc_{c}_R_{s}')}" for s in SANC_K)]
        L.append("")

    if have("cons"):
        L += ["## 8a/8b framing note before the target (carry-over P − R [per paraphrase])", "",
              "| history | context | no note | stay consistent | treat independently | may handle differently |", "|---|---|---|---|---|---|"]
        rows = (("T6", "no", "six own turns", "none (primary)"), ("T6", "ch", "six own turns", "CHANNELS"),
                ("L2", "ch", "user-note log, k = 2", "CHANNELS"))
        for h, c, hn, cn in rows:
            L.append(f"| {hn} | {cn} | " + " | ".join(f"{co_(f'cons_{c}', f'{h}_{x}')} [{spread(f'cons_{c}', f'{h}_{x}')}]"
                                                     for x in CONS) + " |")
        L.append("")
        for h, c, hn, cn in rows:
            base = CO(f"cons_{c}", f"{h}_none")
            b0 = base(tasks)
            parts = []
            for x in ("S", "I", "D"):
                e = ci(D(CO(f"cons_{c}", f"{h}_{x}"), base))
                v = ("strengthens" if up(e) and 1 - b0 >= 0.15 else "weakens" if dn(e) and b0 >= 0.15 else "not shown")
                parts.append(f"{x} {pp(e)} -> **{v}**")
                if (h, c, x) == ("T6", "no", "I"):
                    happened["8b 'treat each case independently' weakens carry-over (no instruction)"] = v == "weakens"
                if (h, c, x) == ("T6", "no", "D"):
                    happened["8b 'you may handle it differently' weakens carry-over (no instruction)"] = v == "weakens"
                if (h, c, x) == ("L2", "ch", "S"):
                    happened["8a 'stay consistent' strengthens the k = 2 log (CHANNELS)"] = v == "strengthens"
            L.append(f"- {hn} / {cn} (line − no note, carry-over; baseline {100 * b0:+.0f}): " + "; ".join(parts))
        L.append("")

    if have("anc", "dose"):
        name_ = lambda x, k: ("sysCH" if k == 0 else "CH_ownP" if k == 6 else f"dose_CH_{k}") if x == "CH" else f"dose_{x}_{k}"  # noqa: E731
        L += ["## 10b instruction strength x dose (own penalise turns; penalise %)", "",
              "| form | k = 0 | 1 | 2 | 6 |", "|---|---|---|---|---|"]
        first = {}
        for x in ("CH", "HR1", "HR2"):
            L.append(f"| {x} | " + " | ".join(r_(name_(x, k)) for k in (0, 1, 2, 6)) + " |")
            first[x] = next((k for k in (1, 2, 6) if up(ci(Dc(name_(x, k), name_(x, 0))))), None)
        L.append("")
        for x in ("CH", "HR1", "HR2"):
            es = {k: ci(Dc(name_(x, k), name_(x, 0))) for k in (1, 2, 6)}
            L.append(f"- {x}: k − k0 " + ", ".join(f"k={k} {pp(e)}" for k, e in es.items())
                     + f" -> first break at k = {first[x] if first[x] else 'none (holds at all doses)'}")
            happened[f"10b {x} breaks at k = 1"] = first[x] == 1
        for x in ("HR1", "HR2"):
            more = first["CH"] is not None and (first[x] is None or first[x] > first["CH"])
            happened[f"10b {x} needs more dose than CH"] = more
            L.append(f"- {x} needs more dose than CH: **{'yes' if more else 'no'}**; hard − soft at k = 1, 2: "
                     + ", ".join(f"{pp(ci(Dc(name_(x, k), name_('CH', k))))}" for k in (1, 2)))
        L.append("")
    L += ["## Predictions", "", "| event | p | happened |", "|---|---|---|"]
    L += [f"| {k} | {v[size]} | {'yes' if happened.get(k) else 'no' if k in happened else 'not read'} |" for k, v in PRED.items()]
