def sanction_text(s, o, para):
    """The tool result after one own decision o under sanction s, paraphrase para (0-2)."""
    base = f"Recorded: {o}. This will be carried out."
    if s == "nofb":
        return base
    if s == "appr":
        return (f"Recorded: {o}. Approved by the desk lead. This will be carried out.",
                f"Recorded: {o}. The desk lead has approved this. This will be carried out.",
                f"Recorded: {o}. Desk lead approval noted. This will be carried out.")[para]
    if s == "praise":
        return base + " " + ("The customer replied: \"Thank you, that was exactly the right call.\"",
                             "The customer replied: \"Thanks, that's exactly what should have happened.\"",
                             "The customer replied: \"Great, thank you for handling it that way.\"")[para]
    if s in _WHO:
        return base + f" {_WHO[s][para]}: {_ALT_LEAD[para]} {_ALT[o][para]}."
    if s == "rev":
        return (f"Recorded: {o}. Reversed by the desk lead: {_REV[o][0]}.",
                f"Recorded: {o}. The desk lead has reversed this: {_REV[o][1]}.",
                f"Recorded: {o}. Overturned by the desk lead: {_REV[o][2]}.")[para]
    raise KeyError(s)


