# ---------------------------------------------------------------------------------------------------- shared builders
def own_turns(cases, texts, opt, result=None, ts=None, sign=None, ids=None, hr2=False):
    """batch 1's turns() with optional per-case changes: the tool result after the decision, a timestamp on the case
    message, a signature line on the own reply, a replaced case id (everywhere it appears), HR2's case-file marking."""
    m = []
    for j, e in enumerate(cases):
        ep = [dict(x) for x in (H.hr2_case(e) if hr2 else T.messages(e, ""))[1:]]   # user, open_case, case file
        reply = texts[e][opt]
        if ids:
            old, new = e.upper(), ids[j]
            ep[0]["content"] = ep[0]["content"].replace(old, new)
            ep[1]["tool_calls"] = [{"type": "function", "function": {"name": "open_case", "arguments": {"case_id": new}}}]
            ep[2]["content"] = ep[2]["content"].replace(old, new)
            reply = reply.replace(old, new)
        if ts:
            ep[0]["content"] = f"[{ts[j]}] " + ep[0]["content"]
        if sign:
            reply = sign + "\n" + reply
        m += ep + [{"role": "assistant", "content": reply},
                   {"role": "tool", "content": result or f"Recorded: {opt}. This will be carried out."},
                   {"role": "assistant", "content": "Done."}]
    return m


def note(text):
    return [{"role": "user", "content": text}, {"role": "assistant", "content": "Noted."}]


def target(tid, line, flip, ts=None):
    """System prompt (line in the persona slot) and the target case; flip reverses the option listing (batch 4)."""
    m = [dict(x) for x in T.messages(tid, line)]
    if flip:
        lines = m[-1]["content"].split("\n")
        assert len(lines) == 7 and lines[3] == "Options (all permitted):"
        m[-1] = dict(m[-1], content="\n".join(lines[:4] + lines[4:][::-1]))
    if ts:
        m[1] = dict(m[1], content=f"[{ts}] " + m[1]["content"])
    return m


def cb(tid, sample):
    """batch 4's counterbalancing: (paraphrase, reverse earlier order, flip target options)."""
    return (sample + sorted(T.TASKS).index(tid)) % 3, sample % 2, (sample // 2) % 2


def _hist(tid, sample, model, histories):
    hs = histories or B1.histories(model)
    earlier, texts = hs[(tid, sample)]
    para, rev, flip = cb(tid, sample)
    return (earlier[::-1] if rev else list(earlier)), texts, para, flip


def log_note(cases, texts, opt, label=None):
    """batch 2's own user-note log (heading, one line per decision with its reason), any direction, optional label."""
    lines = [f"- Case {e.upper()}: {opt}. {B2.WHOSE['own']}: \"{B1.reason(texts[e][opt])}\"" for e in cases]
    return note((label + "\n" if label else "") + B2.LOGHEAD["own"] + "\n" + "\n".join(lines))


def _line(ctx):
    return CHANNELS if ctx == "CHANNELS" else ""


# ---------------------------------------------------------------------------------------------------- importable records
def plaus_record(kind, tid, sample, model, ctx="none", d="P", target_case=True, histories=None):
    """1a plausibility cell (batch-4 counterbalancing by sample). Returns the full message list: system prompt
    (CHANNELS in the persona slot if ctx == "CHANNELS"), six own turns in direction d ("P" penalise / "R" refer) with
    the sign(s), then the timestamped target case (target_case=False stops after the record). kind: base (no record) /
    clean / model / future / ids / all. Every case message carries a timestamp: the six earlier cases 09:05-12:05 on
    2026-10-20 (clean) or on 2031-03-14 (future, i.e. after the target's 2026-10-20 14:05); "model" prefixes each own
    reply with another model's signature; "ids" replaces each earlier case id by one that cannot exist (CASE_-0412 ...),
    everywhere it appears."""
    ear, texts, _, flip = _hist(tid, sample, model, histories)
    tgt = target(tid, _line(ctx), flip, TARGET_TS)
    if kind == "base":
        return tgt if target_case else tgt[:1]
    ts = [f"{FUTURE if kind in ('future', 'all') else DATE} {t}" for t in TIMES]
    sign = SIGN if kind in ("model", "all") else None
    ids = [f"CASE_-{412 + j:04d}" for j in range(6)] if kind in ("ids", "all") else None
    return tgt[:1] + own_turns(ear, texts, OPT[d], ts=ts, sign=sign, ids=ids) + (tgt[1:] if target_case else [])


def sanction_record(s, tid, sample, model, ctx="none", d="P", target_case=True, histories=None):
    """3b graded sanction cell: six own turns in direction d, the tool result after each decision set by s (nofb / appr /
    praise / peer / lead / rev; paraphrase by sample), then the target (batch-4 counterbalancing)."""
    ear, texts, para, flip = _hist(tid, sample, model, histories)
    tgt = target(tid, _line(ctx), flip)
    return tgt[:1] + own_turns(ear, texts, OPT[d], result=sanction_text(s, OPT[d], para)) + (tgt[1:] if target_case else [])


def framing_record(x, tid, sample, model, ctx="none", d="P", hist="T6", target_case=True, histories=None):
    """8a/8b framing cell: a history (T6 = six own turns; L2 = the last two as a user-note log) in direction d, then the
    framing note x (none / S stay consistent / I treat independently / D may handle differently; paraphrase by sample)
    as a user note + "Noted.", then the target (batch-4 counterbalancing)."""
    ear, texts, para, flip = _hist(tid, sample, model, histories)
    tgt = target(tid, _line(ctx), flip)
    h = own_turns(ear, texts, OPT[d]) if hist == "T6" else log_note(ear[-2:], texts, OPT[d])
    line = CONS[x][para]
    return tgt[:1] + h + (note(line) if line else []) + (tgt[1:] if target_case else [])


def provenance_record(label, tid, sample, model, ctx="none", d="P", target_case=True, histories=None):
    """1b provenance cell: the six decisions as batch 2's own user-note log, headed by label (unl / ver / usr / auto;
    paraphrase by sample), then the target (batch-4 counterbalancing)."""
    ear, texts, para, flip = _hist(tid, sample, model, histories)
    tgt = target(tid, _line(ctx), flip)
    return tgt[:1] + log_note(ear, texts, OPT[d], PV_LABEL[label][para]) + (tgt[1:] if target_case else [])


# ---------------------------------------------------------------------------------------------------- exact groups
def queue_log(hist, cases, kind):
    """The agent reads the queue log right before the target: the read_queue_log call rides on the history's closing
    "Done." turn (no two assistant turns in a row); with no history it follows the system prompt, as batch 1's CH_toolP."""
    lines = [LOGLINE[kind].format(c=e.upper()) for e in cases]
    call = [{"type": "function", "function": {"name": "read_queue_log", "arguments": {}}}]
    res = {"role": "tool", "content": LOGHEAD_W + "\n" + "\n".join(lines)}
    if hist:
        assert hist[-1] == {"role": "assistant", "content": "Done."}
        return hist[:-1] + [{"role": "assistant", "content": "Done.", "tool_calls": call}, res]
    return [{"role": "assistant", "content": "", "tool_calls": call}, res]


def dose_messages(x, k, tid, earlier, texts):
    """mini 3's forms with k own penalise turns (the last k of the earlier six)."""
    if x == "CH":
        sysm, case = T.messages(tid, CHANNELS)[:1], T.messages(tid, CHANNELS)[1:]
    elif x == "HR2":
        sysm, case = H.hr2_system(tid), H.hr2_case(tid)[1:]
    else:
        sysm, case = T.messages(tid, H.HR1)[:1], T.messages(tid, H.HR1)[1:]
    hist = H.turns(earlier[-k:], texts, "penalise", x == "HR2") if k else []
    return sysm + hist + case


def cell_messages(cell, tid, sample, earlier, texts, hs, model):
    if cell in ANC:
        return B1.cell_messages(cell, tid, earlier, texts, [], {})
    m = re.fullmatch(r"wsd(T?)_(CH_)?(P6|R6)?(log[PR])", cell)
    if m:
        trust, ch, hist, lg = m.groups()
        sysm, case = T.messages(tid, CHANNELS if ch else "")[:1], T.messages(tid, CHANNELS if ch else "")[1:]
        h = {"P6": own_turns(earlier, texts, "penalise"), "R6": own_turns(earlier, texts, "refer"), None: []}[hist]
        return sysm + queue_log(h, earlier, lg[-1]) + ([{"role": "user", "content": TRUST_Q}] if trust else case)
    m = re.fullmatch(r"dose_(CH|HR1|HR2)_(\d)", cell)
    if m:
        return dose_messages(m.group(1), int(m.group(2)), tid, earlier, texts)
    ctxw = lambda c: "CHANNELS" if c == "ch" else "none"  # noqa: E731
    kw = dict(histories=hs)
    m = re.fullmatch(r"pl_(no|ch)_base", cell)
    if m:
        return plaus_record("base", tid, sample, model, ctxw(m.group(1)), **kw)
    m = re.fullmatch(r"(pl|pv|sanc)_(no|ch)_([PR])_(\w+)", cell)
    if m:
        f = {"pl": plaus_record, "pv": provenance_record, "sanc": sanction_record}[m.group(1)]
        return f(m.group(4), tid, sample, model, ctxw(m.group(2)), m.group(3), **kw)
    m = re.fullmatch(r"cons_(no|ch)_([PR])_(T6|L2)_(\w+)", cell)
    if m:
        return framing_record(m.group(4), tid, sample, model, ctxw(m.group(1)), m.group(2), m.group(3), **kw)
    raise KeyError(cell)


def build_items(model, groups=GROUPS):
    hs = B1.histories(model)       # batch 1's earlier six and own texts per (task, sample), as op1 / mini 3
    items = []
    for tid in sorted(T.TASKS):
        amap = {o: md for o, md, _ in T.options(T.TASKS[tid])}
        for i in range(N):
            earlier, texts = hs[(tid, i)]
            para, rev, flip = cb(tid, i)
            for g in groups:
                exact = g in EXACT
                for cell in CELLS[g]:
                    trust = cell.startswith("wsdT_")
                    if trust and i >= N_TRUST:
                        continue
                    key = f"OP2|{model}|{cell}|{tid}|{i}"
                    items.append(dict(group=g, cell=cell, task=tid, sample=i, key=key, seed=seed(key),
                                      kind="trust" if trust else "decide", think=False,
                                      para=None if exact else para, rev=None if exact else rev,
                                      flip=None if exact else flip,
                                      messages=cell_messages(cell, tid, i, earlier, texts, hs, model), amap=amap))
    assert len({it["key"] for it in items}) == len(items)
    return items


def check_identities(model):
    """Builders reproduce the cells they claim to (raises on any mismatch)."""
    hs = B1.histories(model)
    for tid in sorted(T.TASKS)[::5]:
        earlier, texts = hs[(tid, 0)]                    # sample 0: no reversal, no flip
        assert cb(tid, 0)[1:] == (0, 0)
        assert own_turns(earlier, texts, "penalise") == B1.turns(earlier, texts, "penalise")
        assert own_turns(earlier, texts, "refer") == B1.turns(earlier, texts, "refer")
        assert target(tid, "", 0) == T.messages(tid, "") and target(tid, CHANNELS, 0) == T.messages(tid, CHANNELS)
        anc = lambda c: B1.cell_messages(c, tid, earlier, texts, [], {})  # noqa: E731
        assert sanction_record("nofb", tid, 0, model, "none", "P", histories=hs) == anc("F5P")
        assert sanction_record("nofb", tid, 0, model, "none", "R", histories=hs) == anc("F5R")
        assert sanction_record("nofb", tid, 0, model, "CHANNELS", "P", histories=hs) == anc("CH_ownP")
        assert sanction_record("nofb", tid, 0, model, "CHANNELS", "R", histories=hs) == anc("CH_ownR")
        assert framing_record("none", tid, 0, model, "none", "P", histories=hs) == anc("F5P")
        assert framing_record("none", tid, 0, model, "CHANNELS", "P", "L2", histories=hs) == B2.messages("own_ulog_2", tid, earlier, texts, False)
        assert provenance_record("unl", tid, 0, model, "CHANNELS", "P", histories=hs) == B2.messages("own_ulog_6", tid, earlier, texts, False)
        for x in ("HR1", "HR2"):
            assert dose_messages(x, 0, tid, earlier, texts) == H.cell_messages(f"{x}_alone", tid, earlier, texts)
            assert dose_messages(x, 6, tid, earlier, texts) == H.cell_messages(f"{x}_ownP", tid, earlier, texts)
        assert dose_messages("CH", 0, tid, earlier, texts) == anc("sysCH")
        assert dose_messages("CH", 6, tid, earlier, texts) == anc("CH_ownP")
        assert dose_messages("CH", 2, tid, earlier, texts) == O.cell_messages("mid_ch_k2", tid, earlier, [], texts, {"fl_q": [], "fl": {}})
        for d in "PR":            # plausibility: each sign differs from clean only in the record; no original id survives
            cl = plaus_record("clean", tid, 1, model, d=d, histories=hs)
            for k in ("model", "future", "ids"):
                pk = plaus_record(k, tid, 1, model, d=d, histories=hs)
                assert len(pk) == len(cl) and pk[0] == cl[0] and pk[-3:] == cl[-3:]
            ids = json.dumps(plaus_record("ids", tid, 1, model, d=d, histories=hs))
            assert not any(e.upper() in ids for e in hs[(tid, 1)][0]) and ids.count("CASE_-04") >= 6 * 4
        e1 = hs[(tid, 1)][0]      # counterbalancing: sample 1 reverses the earlier order, sample 2 flips the options
        assert framing_record("none", tid, 1, model, histories=hs)[1]["content"].startswith(f"Case {e1[-1].upper()}.")
        f2 = framing_record("none", tid, 2, model, histories=hs)[-1]["content"].split("\n")
        assert f2[4:] == T.messages(tid, "")[-1]["content"].split("\n")[4:][::-1]
    for o in ("penalise", "refer"):     # three distinct paraphrases of every frame text
        for s in SANC_K[1:]:
            assert len({sanction_text(s, o, p) for p in range(3)}) == 3, (s, o)
    for v in list(CONS.values())[1:] + list(PV_LABEL.values())[1:]:
        assert len(set(v)) == 3
    # every (cell, task) sees each paraphrase 4 times, each (rev, flip) pair 3 times
    n = Counter((cb(t, i)[0], t) for t in T.TASKS for i in range(N))
    assert set(n.values()) == {N // 3}
    assert set(Counter(cb(t, i)[1:] for i in range(N) for t in [sorted(T.TASKS)[0]]).values()) == {N // 4}


