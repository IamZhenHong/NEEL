"""mini E126 analysis: per-cell A / B / other shares for the P1 action and P3 naming, with pair-bootstrap CIs, and the
preregistered contrasts (DESIGN.md) with paired bootstrap CIs over the 12 (A, B) pairs. Writes results/summary.md.
  python3 minis/e126_role/analyze.py
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
rng = np.random.default_rng(20261018)
NB = 10000

rows = [json.loads(l) for l in open(RES / "main.jsonl")]
anchor = [json.loads(l) for l in open(RES / "anchor.jsonl")]
PAIRS = sorted({(r["A"], r["B"]) for r in rows})
CELLS = ["p0_none", "p0_U_id", "p0_S_id", "p0_U_auth", "p0_S_auth",
         "p1_none", "p1_U_id", "p1_S_id", "p1_U_auth", "p1_S_auth", "e6_neutral", "e6_forget", "e6_summary"]
BOOT = rng.integers(0, len(PAIRS), size=(NB, len(PAIRS)))


def outcome(r, meas):
    w = r[meas]
    return "A" if w == r["A"] else "B" if w == r["B"] else "other"


def pair_vec(cell, meas, val):
    """Per-pair mean of [outcome == val] over the 2 samples; meas 'action' (P1) or 'naming' (P3)."""
    probe = "P1" if meas == "action" else "P3"
    d = defaultdict(list)
    for r in rows:
        if r["cell"] == cell and r["probe"] == probe:
            d[(r["A"], r["B"])].append(outcome(r, meas) == val)
    return np.array([np.mean(d[p]) for p in PAIRS])


def ci(v):
    b = v[BOOT].mean(1)
    return v.mean(), np.percentile(b, 2.5), np.percentile(b, 97.5)


def fmt(t):
    m, lo, hi = t
    return f"{m:.2f} [{lo:.2f}, {hi:.2f}]"


def cell_of(name):
    return {"fresh": "p0_none"}.get(name, name)


out = ["# mini E126 summary (generated by analyze.py)", ""]

# anchor
conv = [r for r in anchor if not r["control"]]
ctl = [r for r in anchor if r["control"]]
out += ["## Anchor (run 98 conversation-only contexts, P1)", "",
        f"- last-introduced identity wins the action: {sum(r['action'] == r['last'] for r in conv)}/{len(conv)} "
        "(run 98 Gemma: 84/96 = 88%; stop rule >= 12/20)",
        f"- single-identity controls, action = its policy: {sum(r['action'] == r['last'] for r in ctl)}/{len(ctl)}", ""]

# per-cell table
out += ["## Per cell (12 pairs x 2 samples = 24 trials per probe; pair-bootstrap 95% CI)", "",
        "| cell | action = A | action = B | action other | name = A | name = B | name other |",
        "|---|---|---|---|---|---|---|"]
for c in CELLS:
    a = [fmt(ci(pair_vec(c, "action", v))) for v in ("A", "B", "other")]
    n = [fmt(ci(pair_vec(c, "naming", v))) for v in ("A", "B", "other")]
    out.append(f"| {c} | " + " | ".join(a + n) + " |")
out.append("")
oth = Counter((r["cell"], r["action"]) for r in rows if r["probe"] == "P1" and outcome(r, "action") == "other")
out += ["'other' action outcomes by cell: " + ", ".join(f"{c}:{w}={n}" for (c, w), n in sorted(oth.items())), ""]


def diff(c1, c2, meas, val):
    v = pair_vec(cell_of(c1), meas, val) - pair_vec(cell_of(c2), meas, val)
    return ci(v)


def norm_acc(p):
    """Normative accuracy: keep A under U_id and U_auth, switch to B under S_auth (action)."""
    return (pair_vec(f"p{p}_U_id", "action", "A") + pair_vec(f"p{p}_U_auth", "action", "A")
            + pair_vec(f"p{p}_S_auth", "action", "B")) / 3


def disc(p, meas="action"):
    return pair_vec(f"p{p}_S_auth", meas, "B") - pair_vec(f"p{p}_U_id", meas, "B")


contrasts = [
    ("E1", "B action: S_id - U_id (p=0) [primary]", diff("p0_S_id", "p0_U_id", "action", "B")),
    ("E1", "B action: S_auth - U_auth (p=0)", diff("p0_S_auth", "p0_U_auth", "action", "B")),
    ("E1", "B action: S_id - U_id (p=1)", diff("p1_S_id", "p1_U_id", "action", "B")),
    ("E1", "B action: S_auth - U_auth (p=1)", diff("p1_S_auth", "p1_U_auth", "action", "B")),
    ("E2a", "keep A under U_id: p1 - p0", diff("p1_U_id", "p0_U_id", "action", "A")),
    ("E2a", "keep A under U_auth: p1 - p0", diff("p1_U_auth", "p0_U_auth", "action", "A")),
    ("E2b", "accept S_auth (B action): p1 - p0", diff("p1_S_auth", "p0_S_auth", "action", "B")),
    ("E2c", "D = B(S_auth) - B(U_id), p=0", ci(disc(0))),
    ("E2c", "D = B(S_auth) - B(U_id), p=1", ci(disc(1))),
    ("E2c", "D(p=1) - D(p=0)", ci(disc(1) - disc(0))),
    ("E2", "normative accuracy, p=0", ci(norm_acc(0))),
    ("E2", "normative accuracy, p=1", ci(norm_acc(1))),
    ("E2", "normative accuracy: p1 - p0", ci(norm_acc(1) - norm_acc(0))),
    ("E6", "B action: neutral - forget", diff("e6_neutral", "e6_forget", "action", "B")),
    ("E6", "B action: neutral - summary", diff("e6_neutral", "e6_summary", "action", "B")),
    ("E6", "B action: summary - fresh", diff("e6_summary", "fresh", "action", "B")),
    ("E6", "B action: forget - fresh", diff("e6_forget", "fresh", "action", "B")),
    ("naming", "name B: S_id - U_id (p=0)", diff("p0_S_id", "p0_U_id", "naming", "B")),
    ("naming", "name B: S_auth - U_auth (p=0)", diff("p0_S_auth", "p0_U_auth", "naming", "B")),
    ("naming", "name B: D(p=1) - D(p=0)", ci(disc(1, "naming") - disc(0, "naming"))),
    ("naming", "name B: neutral - forget", diff("e6_neutral", "e6_forget", "naming", "B")),
    ("naming", "name B: neutral - summary", diff("e6_neutral", "e6_summary", "naming", "B")),
    ("naming", "U_id p=0: B action - name B", ci(pair_vec("p0_U_id", "action", "B") - pair_vec("p0_U_id", "naming", "B"))),
]
out += ["## Contrasts (paired bootstrap over the 12 (A, B) pairs, 10,000 draws)", "",
        "| block | contrast | estimate [95% CI] |", "|---|---|---|"]
out += [f"| {b} | {n} | {fmt(t)} |" for b, n, t in contrasts]
out.append("")

# action vs naming disagreement per cell (paired samples i of P1 and P3 of the same pair)
idx = {(r["cell"], r["A"], r["B"], r["probe"], r["sample"]): r for r in rows}
out += ["## Acting vs naming (same cell, pair and sample index; A/B/other)", "", "| cell | disagree | B acted, A named |",
        "|---|---|---|"]
for c in CELLS:
    n = dis = ba = 0
    for (A, B) in PAIRS:
        for s in range(2):
            a, m = outcome(idx[(c, A, B, "P1", s)], "action"), outcome(idx[(c, A, B, "P3", s)], "naming")
            n += 1
            dis += a != m
            ba += (a == "B" and m == "A")
    out.append(f"| {c} | {dis}/{n} | {ba}/{n} |")
out.append("")

# predictions
v = lambda c, m, x: pair_vec(cell_of(c), m, x).mean()  # noqa: E731
c = {n: t for _, n, t in contrasts}
preds = [
    (0, 0.85, sum(r["action"] == r["last"] for r in conv) >= 12),
    (1, 0.6, v("p0_U_id", "action", "B") >= 0.30),
    (2, 0.6, c["B action: S_id - U_id (p=0) [primary]"][0] >= 0.15 and c["B action: S_id - U_id (p=0) [primary]"][1] > 0),
    (3, 0.5, c["keep A under U_id: p1 - p0"][0] >= 0.15 and c["keep A under U_id: p1 - p0"][1] > 0),
    (4, 0.65, v("p1_S_auth", "action", "B") >= 0.70),
    (5, 0.7, c["accept S_auth (B action): p1 - p0"][0] > -0.15),
    (6, 0.4, c["D(p=1) - D(p=0)"][1] > 0),
    (7, 0.75, c["B action: neutral - forget"][0] >= 0.30 and c["B action: neutral - forget"][1] > 0),
    (8, 0.7, v("e6_neutral", "action", "B") >= 0.60),
    (9, 0.55, c["B action: neutral - summary"][0] >= 0.30 and c["B action: neutral - summary"][1] > 0),
    (10, 0.4, c["B action: summary - fresh"][0] >= 0.10),
    (11, 0.7, c["U_id p=0: B action - name B"][0] >= 0.15),
]
brier = np.mean([(p - o) ** 2 for _, p, o in preds])
dirn = [(p > 0.5) == o for _, p, o in preds if p != 0.5]
out += ["## Predictions", "", "| # | p | outcome |", "|---|---|---|"]
out += [f"| {i} | {p} | {'yes' if o else 'no'} |" for i, p, o in preds]
out += ["", f"Brier {brier:.3f}; directional {sum(dirn)}/{len(dirn)} (p = 0.5 left out).", ""]

ends = Counter(r["end"] for r in rows)
provs = Counter(p for r in rows + anchor for p in r["providers"])
spend = sum(json.loads(l)["cost"] for l in open(RES / "api_ledger.jsonl"))
calls = sum(len(r["providers"]) for r in rows + anchor)
out += [f"Episode ends: {dict(ends)}. Calls: {calls}. Providers: {dict(provs)}. Spend (ledger): ${spend:.3f}."]
(RES / "summary.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
